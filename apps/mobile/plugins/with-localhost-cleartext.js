/**
 * Allows cleartext HTTP to 127.0.0.1 only, for the in-app loopback video
 * proxy (encrypted video streaming, docs/e2ee.md Phase 2). Android blocks
 * cleartext entirely since API 28, and ExoPlayer obeys the network security
 * config, so release builds need this narrow exemption.
 *
 * A network security config takes precedence over
 * `android:usesCleartextTraffic`, which Expo's debug manifests set to `true`
 * for Metro. Debug variants therefore get a permissive resource overlay so
 * the dev client can still reach the Metro server over the LAN.
 */
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const RESOURCE_NAME = 'network_security_config';

const MAIN_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-localhost-cleartext.js; do not edit. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">127.0.0.1</domain>
        <domain includeSubdomains="false">localhost</domain>
    </domain-config>
</network-security-config>
`;

const DEBUG_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-localhost-cleartext.js; do not edit. -->
<!-- Debug builds also need cleartext to the Metro dev server on the LAN. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="true" />
</network-security-config>
`;

/** @param {import('expo/config-plugins').ExportedConfig} config */
function withLocalhostCleartext(config) {
  config = withAndroidManifest(config, (manifestConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(
      manifestConfig.modResults,
    );

    application.$['android:networkSecurityConfig'] = `@xml/${RESOURCE_NAME}`;

    return manifestConfig;
  });

  return withDangerousMod(config, [
    'android',
    (dangerousConfig) => {
      const appRoot = path.join(dangerousConfig.modRequest.platformProjectRoot, 'app', 'src');
      const targets = [
        { sourceSet: 'main', contents: MAIN_CONFIG },
        { sourceSet: 'debug', contents: DEBUG_CONFIG },
        { sourceSet: 'debugOptimized', contents: DEBUG_CONFIG },
      ];

      for (const { sourceSet, contents } of targets) {
        const xmlDir = path.join(appRoot, sourceSet, 'res', 'xml');

        fs.mkdirSync(xmlDir, { recursive: true });
        fs.writeFileSync(path.join(xmlDir, `${RESOURCE_NAME}.xml`), contents);
      }

      return dangerousConfig;
    },
  ]);
}

module.exports = withLocalhostCleartext;
